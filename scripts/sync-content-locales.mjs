import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { parseAboutReadme } from '../app/utils/about-readme.ts'
import { supportedLocales } from '../shared/locales.ts'
import { guides } from '../shared/seo/guides.ts'
import { focusedGuideLocales, focusedGuideSlugs } from '../shared/seo/routes.ts'

const root = new URL('../', import.meta.url)
const read = (path) => JSON.parse(readFileSync(new URL(path, root), 'utf8'))
const write = (path, value) =>
  writeFileSync(new URL(path, root), JSON.stringify(value, null, 2) + '\n')
// These three About pages also read the README directly at runtime/build time.
for (const [language, path] of Object.entries({
  en: 'docs/readme/README.en.md',
  'zh-CN': 'docs/readme/README.zh-CN.md',
  'zh-TW': 'README.md'
})) {
  const target = `i18n/content/${language}.json`
  const content = read(target)
  content.about = parseAboutReadme(readFileSync(new URL(path, root), 'utf8'))
  write(target, content)
}
// English and Simplified Chinese guide bodies are authored in shared/seo/guides.ts.
for (const language of ['en', 'zh-CN']) {
  const target = `i18n/content/${language}.json`
  const content = read(target)
  content.guides = guides[language]
  write(target, content)
}
// Focused guides exist in a few languages only and are not in the main dictionary,
// so their SEO titles and descriptions are generated from the article files.
const focusedMeta = {}
for (const slug of focusedGuideSlugs) {
  focusedMeta[slug] = {}
  for (const language of focusedGuideLocales) {
    const guide = read(`i18n/content/${language}.json`).guides.find((item) => item.slug === slug)
    if (!guide) throw new Error(`Missing ${language} guide: ${slug}`)
    const { title, description, sources } = guide
    focusedMeta[slug][language] = { title, description, sources }
  }
}
writeFileSync(
  new URL('shared/seo/focused-guide-meta.ts', root),
  '// Generated by scripts/sync-content-locales.mjs from i18n/content. Do not edit by hand.\n' +
    `export const focusedGuideMeta = ${JSON.stringify(focusedMeta, null, 2)} as const\n`
)
const lite = read('shared/lite-copy.json')
mkdirSync(new URL('public/lite-assets/locales/', root), { recursive: true })
for (const { code } of supportedLocales) {
  if (!lite[code]) throw new Error(`Missing Lite translation: ${code}`)
  writeFileSync(
    new URL(`public/lite-assets/locales/${code}.js`, root),
    '/* Generated by scripts/sync-content-locales.mjs. ES5 only. */\n' +
      'window.LiteMessages = window.LiteMessages || {};\n' +
      `window.LiteMessages[${JSON.stringify(code)}] = ${JSON.stringify(lite[code].ui, null, 2)};\n`
  )
}
console.log(
  `Synchronized source articles, focused guide metadata and ${supportedLocales.length} Lite catalogs in ${fileURLToPath(root)}`
)
